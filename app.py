import streamlit as st
from model_utils import ensure_models, predict_bundle

st.set_page_config(page_title="ML Assignment 2", page_icon="🧪", layout="centered")
st.title("ML Assignment 2")
st.caption("ML Assignment 2 demonstration — use for learning only, not real-world decisions.")

@st.cache_resource
def get_bundles():
    return ensure_models()

try:
    titanic_bundle, heart_bundle = get_bundles()
except Exception as e:
    st.error("The models could not be prepared. Check that the dependencies are installed and that the UCI dataset can be downloaded. Details:")
    st.exception(e)
    st.stop()


tab_titanic, tab_heart = st.tabs(["Titanic Survival", "Heart Disease"])
with tab_titanic:
    st.subheader("Titanic Passenger Survival Prediction")
    st.write("Inputs match the assignment's four attributes.")
    with st.form("titanic_form"):
        pclass = st.selectbox("Passenger class", ["First", "Second", "Third"])
        gender = st.selectbox("Gender", ["Female", "Male"])
        sibling = st.selectbox("Sibling count", ["Zero", "One", "Two", "Three"])
        embarked = st.selectbox("Embarkation port", ["Southampton", "Cherbourg", "Queenstown"])
        submit_titanic = st.form_submit_button("Predict survival")
    if submit_titanic:
        try:
            result = predict_bundle(titanic_bundle, {"PClass": pclass, "Gender": gender, "Sibling": sibling, "Embarked": embarked})
            if result == "Yes":
                st.success("Model prediction: survived")
            else:
                st.warning("Model prediction: did not survive")
            st.caption("This uses the 100-row course-provided sample dataset and is only a classroom demo.")
        except Exception as e:
            st.error(f"Prediction failed: {e}")

with tab_heart:
    st.subheader("Heart Disease Prediction")
    st.warning("Educational model only. It cannot diagnose heart disease or replace a health professional.")
    st.write("Exactly four input attributes are used: age, sex, chest pain type and maximum heart rate.")
    with st.form("heart_form"):
        age = st.slider("Age (years)", min_value=20, max_value=90, value=54)
        sex_label = st.selectbox("Sex", ["Female", "Male"])
        cp_label = st.selectbox("Chest pain type", ["Typical angina", "Atypical angina", "Non-anginal pain", "Asymptomatic"])
        thalach = st.slider("Maximum heart rate achieved", min_value=60, max_value=220, value=150)
        submit_heart = st.form_submit_button("Estimate model class")
    if submit_heart:
        values = {"age": float(age), "sex": 0 if sex_label == "Female" else 1,
                  "cp": {"Typical angina": 1, "Atypical angina": 2, "Non-anginal pain": 3, "Asymptomatic": 4}[cp_label],
                  "thalach": float(thalach)}
        try:
            result = predict_bundle(heart_bundle, values)
            if result == "Disease present":
                st.error("Model output: disease present class")
            else:
                st.success("Model output: no disease class")
            st.caption("Do not use this output for medical decisions. The model is trained on a small historical dataset using only four features.")
        except Exception as e:
            st.error(f"Prediction failed: {e}")

st.divider()
st.caption("Datasets: course-provided Titanic sample and UCI Heart Disease (Cleveland) dataset. Models are generated by the notebooks or automatically when the app starts.")
